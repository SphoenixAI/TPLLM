def test_config_from_env_smtp():
    """Test that email config is created from SMTP env vars."""
    import os

    env = {
        "SMTP_HOST": "smtp.test.com",
        "SMTP_PORT": "465",
        "SMTP_USER": "user@test.com",
        "SMTP_PASSWORD": "secret123",
        "EMAIL_FROM": "noreply@test.com",
    }
    with patch.dict(os.environ, env, clear=False):
        from lltpm.config import LLTPMConfig
        cfg = LLTPMConfig.from_env()

        assert cfg.email.enabled is True
        assert cfg.email.api_key == "secret123"
        assert cfg.email.extra["backend"] == "smtp"
        assert cfg.email.extra["smtp_host"] == "smtp.test.com"
        assert cfg.email.extra["smtp_port"] == "465"
        assert cfg.email.extra["from_email"] == "noreply@test.com"


