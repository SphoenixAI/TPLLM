"""Tests for Email Integration and Email Tools."""

from __future__ import annotations

import json
from unittest.mock import MagicMock, patch

from lltpm.config import IntegrationConfig
from lltpm.integrations.email_integration import EmailIntegration


def _make_config(**overrides):
    defaults = {
        "enabled": True,
        "api_key": "test-password",
        "base_url": "",
        "extra": {
            "backend": "smtp",
            "smtp_host": "smtp.example.com",
            "smtp_port": "587",
            "smtp_user": "user@example.com",
            "from_email": "lltpm@example.com",
            "from_name": "LLTPM Agent",
        },
    }
    defaults.update(overrides)
    return IntegrationConfig(**defaults)


def test_email_integration_name():
    email = EmailIntegration(_make_config())
    assert email.name == "email"


def test_email_backend_default():
    cfg = _make_config()
    email = EmailIntegration(cfg)
    assert email._backend == "smtp"


