def test_send_email_smtp_success():
    """Test successful SMTP email delivery with mocked SMTP server."""
    cfg = _make_config()
    email = EmailIntegration(cfg)

    with patch("smtplib.SMTP") as mock_smtp:
        mock_server = MagicMock()
        mock_smtp.return_value.__enter__ = MagicMock(return_value=mock_server)
        mock_smtp.return_value.__exit__ = MagicMock(return_value=False)

        result = email.send_email("alice@example.com", "Test", "<p>Hello</p>")

        assert result["status"] == "sent"
        assert result["backend"] == "smtp"
        assert result["recipients"] == ["alice@example.com"]


