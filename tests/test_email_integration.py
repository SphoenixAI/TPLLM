def test_send_digest():
    """Test digest email with multiple sections."""
    cfg = _make_config()
    email = EmailIntegration(cfg)

    with patch.object(email, "send_email", return_value={"status": "sent"}) as mock:
        sections = [
            {"title": "Status", "content": "<p>All green</p>"},
            {"title": "Risks", "content": "<p>One risk flagged</p>"},
        ]
        result = email.send_digest("alice@example.com", "Weekly Digest", sections)

        assert result["status"] == "sent"
        call_args = mock.call_args
        html_body = call_args[0][2]
        assert "Status" in html_body
        assert "Risks" in html_body
        assert "Generated by LLTPM" in html_body


