"""Live organizational intelligence orchestrator (Commit 30).

Everything below this layer answers a question about the organization.
This layer decides *when those questions get asked again*, and whether
anyone should hear the answer.

The runtime is a scheduler and a judge of significance, not another
intelligence model. It owns the live path — dedupe, temporal ordering,
scope, coalesced recompute, coherent revisions, validity, materiality,
causal compression, attention — and delegates every actual computation
to the domains that own it.

Two invariants define it. Arrival order is never temporal authority: a
late webhook cannot move an approved decision back to pending. And a
stale recommendation can never drive an autonomous action: validation
and finalization happen inside one guarded call, so the world cannot
move in between.

The system's purpose is to absorb organizational complexity, not to
generate work. Silence is a first-class result.

This package composes the domains beneath it and is imported by none of
them.
"""

