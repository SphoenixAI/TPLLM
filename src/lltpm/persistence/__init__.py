"""Durable persistence and deterministic replay.

The runtime makes LLTPM live. This makes it durable, and the whole design
turns on one distinction:

    the journal is the durable historical record of organizational state
    transitions; everything derived from it is a rebuildable projection.

So the acceptance test is a deletion: remove every runtime projection,
artifact, and snapshot, keep only the journal, replay it, and get
semantically equivalent intelligence back.

The reference deployment is one local SQLite file. No Kafka, no Redis,
no Postgres, no object store, no scheduler, no daemon — every backend
sits behind a protocol so a hosted one can be added without changing
anything above this layer.

Three guarantees hold regardless of backend. History is append-only and
hash-chained, so accidental mutation and truncation are loud rather than
silent. Replay never touches the outside world, so rebuilding the past
cannot repeat its consequences. And reproducing what LLTPM concluded
then is kept distinct from what it would conclude now, because those are
different questions.

Nothing here records anybody's activity. Durability must not quietly
become surveillance history.
"""

