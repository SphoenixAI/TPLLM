"""Email integration — SMTP and SendGrid support for notifications and digests.

Supports two backends:
- SMTP (direct) for simple setups
- SendGrid API for production delivery with tracking

All emails use the document generator's HTML templates for consistent branding.
"""

from __future__ import annotations

import json
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Any

from tpllm.integrations.base import Integration, IntegrationError


class EmailIntegration(Integration):
    """Email delivery via SMTP or SendGrid."""

    def __init__(self, config: Any) -> None:
        super().__init__(config)
        self._backend = config.extra.get("backend", "smtp")  # "smtp" or "sendgrid"
        self._smtp_host = config.extra.get("smtp_host", "smtp.gmail.com")
        self._smtp_port = int(config.extra.get("smtp_port", 587))
        self._smtp_user = config.extra.get("smtp_user", "")
        self._smtp_password = config.api_key  # reuse api_key field for password/key
        self._from_email = config.extra.get("from_email", "tpllm@example.com")
        self._from_name = config.extra.get("from_name", "TPLLM Agent")
        self._sendgrid_api_key = config.api_key if self._backend == "sendgrid" else ""

    @property
    def name(self) -> str:
        return "email"

    def test_connection(self) -> bool:
        """Test email connectivity."""
        if self._backend == "smtp":
            try:
                with smtplib.SMTP(self._smtp_host, self._smtp_port, timeout=10) as server:
                    server.ehlo()
                    if self._smtp_port == 587:
                        server.starttls()
                    if self._smtp_user and self._smtp_password:
                        server.login(self._smtp_user, self._smtp_password)
                return True
            except Exception:
                return False
        elif self._backend == "sendgrid":
            return bool(self._sendgrid_api_key)
        return False

    def send_email(
        self,
        to: str | list[str],
        subject: str,
        html_body: str,
        text_body: str = "",
        reply_to: str = "",
    ) -> dict[str, Any]:
        """Send an email. Returns delivery status."""
        recipients = [to] if isinstance(to, str) else to

        if self._backend == "smtp":
            return self._send_smtp(recipients, subject, html_body, text_body, reply_to)
        elif self._backend == "sendgrid":
            return self._send_sendgrid(recipients, subject, html_body, text_body, reply_to)
        else:
            raise IntegrationError(f"Unknown email backend: {self._backend}")

    def send_digest(
        self,
        to: str,
        subject: str,
        sections: list[dict[str, str]],
    ) -> dict[str, Any]:
        """Send a digest email with multiple sections."""
        html_parts = [
            '<div style="font-family: -apple-system, sans-serif; max-width: 600px; margin: 0 auto;">',
            f'<h1 style="border-bottom: 2px solid #2563eb; padding-bottom: 8px;">{subject}</h1>',
        ]

        for section in sections:
            html_parts.append(
                f'<h2 style="color: #334155; margin-top: 20px;">{section.get("title", "")}</h2>'
                f'<div style="padding: 8px 0;">{section.get("content", "")}</div>'
            )

        html_parts.append(
            '<div style="margin-top: 30px; padding-top: 10px; border-top: 1px solid #e2e8f0; '
            'color: #94a3b8; font-size: 11px;">'
            'Generated by TPLLM — AI Technical Program Manager</div>'
            '</div>'
        )

        html_body = "\n".join(html_parts)
        text_body = "\n\n".join(
            f"## {s.get('title', '')}\n{s.get('content', '')}" for s in sections
        )

        return self.send_email(to, subject, html_body, text_body)

    def _send_smtp(
        self,
        recipients: list[str],
        subject: str,
        html_body: str,
        text_body: str,
        reply_to: str,
    ) -> dict[str, Any]:
        """Send via SMTP."""
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = f"{self._from_name} <{self._from_email}>"
        msg["To"] = ", ".join(recipients)
        if reply_to:
            msg["Reply-To"] = reply_to

        if text_body:
            msg.attach(MIMEText(text_body, "plain"))
        msg.attach(MIMEText(html_body, "html"))

        try:
            with smtplib.SMTP(self._smtp_host, self._smtp_port, timeout=30) as server:
                server.ehlo()
                if self._smtp_port == 587:
                    server.starttls()
                if self._smtp_user and self._smtp_password:
                    server.login(self._smtp_user, self._smtp_password)
                server.sendmail(self._from_email, recipients, msg.as_string())

            return {
                "status": "sent",
                "backend": "smtp",
                "recipients": recipients,
            }
        except Exception as e:
            return {
                "status": "failed",
                "backend": "smtp",
                "error": str(e),
            }

    def _send_sendgrid(
        self,
        recipients: list[str],
        subject: str,
        html_body: str,
        text_body: str,
        reply_to: str,
    ) -> dict[str, Any]:
        """Send via SendGrid API (stub — requires sendgrid package)."""
        try:
            import sendgrid
            from sendgrid.helpers.mail import Content, Email, Mail, To

            sg = sendgrid.SendGridAPIClient(api_key=self._sendgrid_api_key)
            from_email = Email(self._from_email, self._from_name)
            to_emails = [To(r) for r in recipients]
            content = Content("text/html", html_body)
            mail = Mail(from_email, to_emails, subject, content)

            if reply_to:
                mail.reply_to = Email(reply_to)

            response = sg.client.mail.send.post(request_body=mail.get())
            return {
                "status": "sent",
                "backend": "sendgrid",
                "status_code": response.status_code,
                "recipients": recipients,
            }
        except ImportError:
            # Fallback: log the email for later sending
            return {
                "status": "queued",
                "backend": "sendgrid",
                "note": "sendgrid package not installed — email queued locally",
                "recipients": recipients,
            }
        except Exception as e:
            return {
                "status": "failed",
                "backend": "sendgrid",
                "error": str(e),
            }
